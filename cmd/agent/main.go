package main

import (
	"context"
	"flag"
	"fmt"
	"log"
	"net"
	"net/url"
	"os"
	"os/signal"
	"strconv"
	"syscall"
	"time"

	"nexus-panel/internal/agent/client"
	"nexus-panel/internal/agent/engine"
	"nexus-panel/internal/agent/security"
)

func main() {
	var (
		masterURL       = flag.String("master", getEnv("NEXUS_MASTER_URL", ""), "Master WebSocket URL (wss://<panel>/api/v1/agent/ws)")
		nodeID          = flag.Uint64("id", getEnvUint64("NEXUS_NODE_ID", 0), "Node ID assigned by Master panel")
		token           = flag.String("token", getEnv("NEXUS_NODE_TOKEN", ""), "Node communication secret token (HMAC key)")
		stateDir        = flag.String("state-dir", getEnv("NEXUS_STATE_DIR", ""), "Private state directory (rule snapshot, tunnel TLS identity, engine configs)")
		allowInsecureWS = flag.Bool("allow-insecure-ws", getEnv("NEXUS_ALLOW_INSECURE_WS", "false") == "true", "Allow plain ws:// to a non-loopback Master (NOT recommended: control channel is unencrypted)")
		masterPinSHA256 = flag.String("master-pin-sha256", getEnv("NEXUS_MASTER_PIN_SHA256", ""), "Optional Master TLS certificate SHA-256 hex fingerprint")
		allowPrivateIPs = flag.Bool("allow-private-targets", getEnv("NEXUS_ALLOW_PRIVATE_TARGETS", "false") == "true", "Allow forwarding to RFC1918 private IPs (disabled by default for Anti-SSRF)")
		minListenPort   = flag.Int("min-port", 1024, "Minimum allowed local listen port")
		maxConnsPerIP   = flag.Int("max-conns-per-ip", 256, "Maximum concurrent connections per client IP")
		reportInterval  = flag.Duration("report-interval", 3*time.Second, "Heartbeat probe & traffic sync interval (default 3s)")
	)
	flag.Parse()

	if *masterURL == "" || *nodeID == 0 || *token == "" {
		log.Fatal("[Agent] -master, -id and -token (or NEXUS_MASTER_URL / NEXUS_NODE_ID / NEXUS_NODE_TOKEN) are required")
	}
	if len(*token) < 16 {
		log.Fatal("[Agent] node token is too short (expected the token generated by the panel)")
	}
	if err := checkMasterURL(*masterURL, *allowInsecureWS); err != nil {
		log.Fatalf("[Agent] %v", err)
	}

	ctx, cancel := signal.NotifyContext(context.Background(), os.Interrupt, syscall.SIGTERM)
	defer cancel()

	secPolicy := security.Policy{
		AllowPrivateTargets: *allowPrivateIPs,
		MinListenPort:       *minListenPort,
		MaxListenPort:       65535,
		MaxConnsPerClientIP: *maxConnsPerIP,
	}

	engMgr, err := engine.NewManager(security.DefaultStateDir(*stateDir), secPolicy)
	if err != nil {
		log.Fatalf("[Agent] Failed to initialize engines: %v", err)
	}
	defer func() {
		log.Println("[Agent] Shutting down forwarding engines...")
		_ = engMgr.Close()
	}()

	// Immediately restore and restart all active forwarding rules from local snapshot upon service boot/restart
	engMgr.RestoreSnapshot(ctx)

	log.Printf("[Agent] Starting Nexus Agent (NodeID=%d, SyncInterval=%s, Anti-SSRF=%v, Engines=%v)",
		*nodeID, *reportInterval, !*allowPrivateIPs, engMgr.SupportedEngines())

	agentCli := client.NewAgentClient(client.Config{
		MasterURL:        *masterURL,
		NodeID:           *nodeID,
		SecretToken:      *token,
		MasterPinSHA256:  *masterPinSHA256,
		AllowPrivateSSRF: *allowPrivateIPs,
		ReportInterval:   *reportInterval,
	}, engMgr)
	agentCli.Run(ctx)
}

// checkMasterURL refuses plaintext control channels to remote hosts unless explicitly allowed.
func checkMasterURL(raw string, allowInsecure bool) error {
	u, err := url.Parse(raw)
	if err != nil {
		return fmt.Errorf("invalid master URL: %v", err)
	}
	switch u.Scheme {
	case "wss":
		return nil
	case "ws":
		host := u.Hostname()
		if host == "localhost" {
			return nil
		}
		if ip := net.ParseIP(host); ip != nil && ip.IsLoopback() {
			return nil
		}
		if allowInsecure {
			log.Printf("[Agent] WARNING: using unencrypted ws:// control channel to %s", host)
			return nil
		}
		return fmt.Errorf("refusing unencrypted ws:// master URL %q; use wss:// or pass -allow-insecure-ws", raw)
	default:
		return fmt.Errorf("master URL must use ws:// or wss:// scheme")
	}
}

func getEnv(key, fallback string) string {
	if v := os.Getenv(key); v != "" {
		return v
	}
	return fallback
}

func getEnvUint64(key string, fallback uint64) uint64 {
	if v := os.Getenv(key); v != "" {
		if n, err := strconv.ParseUint(v, 10, 64); err == nil {
			return n
		}
	}
	return fallback
}
